/**
 * Traduz qualquer nome de classe do DayZ para um nome legível em Português.
 * Se o item não estiver no dicionário estático, aplica regras inteligentes de parsing
 * para prefixos, sufixos, calibres e cores.
 */
export function getItemLabel(className: string | undefined | null): string {
  if (!className) return "";
  const trimmed = className.trim();
  if (DAYZ_ITEM_TRANSLATIONS[trimmed]) {
    return DAYZ_ITEM_TRANSLATIONS[trimmed];
  }

  // Regras dinâmicas de tradução inteligente
  let label = trimmed;

  // Prefixos comuns
  if (label.startsWith("Ammo_")) {
    label = "Munição " + label.replace("Ammo_", "").replace(/_/g, " ");
  } else if (label.startsWith("Mag_")) {
    label = "Carregador " + label.replace("Mag_", "").replace(/_/g, " ");
  } else if (label.startsWith("Sawedoff")) {
    label = label.replace("Sawedoff", "") + " (Cano Serrado)";
  } else if (label.startsWith("Infected")) {
    label = "Zumbi " + label.replace("Infected", "");
  } else if (label.startsWith("Animal")) {
    label = "Animal: " + label.replace("Animal", "");
  } else if (label.startsWith("Vehicle")) {
    label = "Veículo " + label.replace("Vehicle", "");
  }

  // Cores e variações
  label = label
    .replace(/_Green$/i, " (Verde)")
    .replace(/_Black$/i, " (Preto)")
    .replace(/_Blue$/i, " (Azul)")
    .replace(/_Red$/i, " (Vermelho)")
    .replace(/_Yellow$/i, " (Amarelo)")
    .replace(/_White$/i, " (Branco)")
    .replace(/_Orange$/i, " (Laranja)")
    .replace(/_Grey$/i, " (Cinza)")
    .replace(/_Brown$/i, " (Marrom)")
    .replace(/_Tan$/i, " (Bege)")
    .replace(/_Camo$/i, " (Camuflado)")
    .replace(/_Autumn$/i, " (Outono)")
    .replace(/_Summer$/i, " (Verão)")
    .replace(/_Woodland$/i, " (Floresta)")
    .replace(/_Desert$/i, " (Deserto)")
    .replace(/_Mossy$/i, " (Musgo)");

  return label;
}
